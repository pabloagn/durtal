export const ebookUploadCapacity = pgTable("ebook_upload_capacity", {
  volumeId: uuid("volume_id").primaryKey(),
  bindingSha256: text("binding_sha256").notNull(),
  quotaBytes: bigint("quota_bytes", { mode: "number" }).notNull().default(34359738368),
  freeReserveBytes: bigint("free_reserve_bytes", { mode: "number" }).notNull().default(8589934592),
  globalAllowanceBytes: bigint("global_allowance_bytes", { mode: "number" }).notNull().default(83886080),
  reservedBytes: bigint("reserved_bytes", { mode: "number" }).notNull().default(83886080),
  unaccountedBytes: bigint("unaccounted_bytes", { mode: "number" }).notNull().default(0),
  revision: bigint("revision", { mode: "number" }).notNull().default(0),
  state: text("state", { enum: ["recovering", "ready", "quiescing", "blocked"] }).notNull().default("recovering"),
  ownerToken: uuid("owner_token"),
  ownerFence: bigint("owner_fence", { mode: "number" }).notNull().default(0),
  ownerIdentity: jsonb("owner_identity").$type<Record<string, JsonValue>>(),
  ownerLeaseExpiresAt: timestamp("owner_lease_expires_at", { withTimezone: true }),
  activePartWriters: integer("active_part_writers").notNull().default(0),
  workerOperationId: uuid("worker_operation_id").references((): AnyPgColumn => ebookUploadOperations.id, { onDelete: "restrict" }),
  workerToken: uuid("worker_token"),
  workerState: text("worker_state", { enum: ["idle", "running", "quiescing"] }).notNull().default("idle"),
  workerLeaseExpiresAt: timestamp("worker_lease_expires_at", { withTimezone: true }),
  allocatedBytes: bigint("allocated_bytes", { mode: "number" }),
  availableBytes: bigint("available_bytes", { mode: "number" }),
  measuredAt: timestamp("measured_at", { withTimezone: true }),
  measurementGeneration: bigint("measurement_generation", { mode: "number" }).notNull().default(0),
  cleanupProof: jsonb("cleanup_proof").$type<Record<string, JsonValue>>(),
  createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
  updatedAt: timestamp("updated_at", { withTimezone: true }).notNull().defaultNow(),
}, (t) => [
  check("ebook_upload_capacity_binding_check", sql`${t.bindingSha256} ~ '^[a-f0-9]{64}$'`),
  check("ebook_upload_capacity_limits_check", sql`${t.quotaBytes} = 34359738368 and ${t.freeReserveBytes} = 8589934592 and ${t.globalAllowanceBytes} = 83886080`),
  check("ebook_upload_capacity_accounting_check", sql`${t.reservedBytes} >= ${t.globalAllowanceBytes} and ${t.unaccountedBytes} >= 0 and ${t.reservedBytes} + ${t.unaccountedBytes} <= ${t.quotaBytes}`),
  check("ebook_upload_capacity_revision_check", sql`${t.revision} >= 0 and ${t.ownerFence} >= 0 and ${t.measurementGeneration} >= 0`),
  check("ebook_upload_capacity_state_check", sql`${t.state} in ('recovering', 'ready', 'quiescing', 'blocked')`),
  check("ebook_upload_capacity_writers_check", sql`${t.activePartWriters} between 0 and 8`),
  check("ebook_upload_capacity_owner_check", sql`(${t.ownerToken} is null and ${t.ownerIdentity} is null and ${t.ownerLeaseExpiresAt} is null) or (${t.ownerToken} is not null and ${t.ownerIdentity} is not null and ${t.ownerLeaseExpiresAt} is not null)`),
  check("ebook_upload_capacity_worker_check", sql`(${t.workerState} = 'idle' and ${t.workerOperationId} is null and ${t.workerToken} is null and ${t.workerLeaseExpiresAt} is null) or (${t.workerState} in ('running', 'quiescing') and ${t.workerOperationId} is not null and ${t.workerToken} is not null and ${t.workerLeaseExpiresAt} is not null)`),
  check("ebook_upload_capacity_measurement_check", sql`(${t.allocatedBytes} is null or ${t.allocatedBytes} >= 0) and (${t.availableBytes} is null or ${t.availableBytes} >= 0)`),
]);

export const ebookUploadOperations = pgTable("ebook_upload_operations", {
  id: uuid("id").primaryKey(),
  idempotencyKey: uuid("idempotency_key").notNull().unique(),
  kind: text("kind", { enum: ["batch", "upload", "admit", "complete", "cancel", "retry", "restore", "undo"] }).notNull(),
  requestSha256: text("request_sha256").notNull(),
  targetFingerprint: text("target_fingerprint").notNull(),
  bindingSha256: text("binding_sha256").notNull(),
  protocolVersion: integer("protocol_version").notNull(),
  parentOperationId: uuid("parent_operation_id").references((): AnyPgColumn => ebookUploadOperations.id, { onDelete: "restrict" }),
  volumeId: uuid("volume_id").notNull().references(() => ebookUploadCapacity.volumeId, { onDelete: "restrict" }),
  runId: uuid("run_id").references(() => ebookIngestRuns.id, { onDelete: "restrict" }),
  ingestItemId: uuid("ingest_item_id").unique().references(() => ebookIngestItems.id, { onDelete: "restrict" }),
  input: jsonb("input").$type<Record<string, JsonValue>>().notNull(),
  progress: jsonb("progress").$type<Record<string, JsonValue>>().notNull().default({}),
  receipt: jsonb("receipt").$type<Record<string, JsonValue>>(),
  receiptStatus: integer("receipt_status"),
  state: text("state", { enum: ["queued", "admitted", "receiving", "ready", "processing", "quiescing", "completed", "failed", "canceled", "expired"] }).notNull().default("queued"),
  sourceSizeBytes: bigint("source_size_bytes", { mode: "number" }),
  reservedBytes: bigint("reserved_bytes", { mode: "number" }).notNull().default(0),
  revision: bigint("revision", { mode: "number" }).notNull().default(0),
  generation: bigint("generation", { mode: "number" }).notNull().default(0),
  leaseToken: uuid("lease_token"),
  leaseExpiresAt: timestamp("lease_expires_at", { withTimezone: true }),
  retentionExpiresAt: timestamp("retention_expires_at", { withTimezone: true }),
  effectCommittedAt: timestamp("effect_committed_at", { withTimezone: true }),
  cleanupVerifiedAt: timestamp("cleanup_verified_at", { withTimezone: true }),
  reservationReleasedAt: timestamp("reservation_released_at", { withTimezone: true }),
  createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
  updatedAt: timestamp("updated_at", { withTimezone: true }).notNull().defaultNow(),
}, (t) => [
  check("ebook_upload_operations_kind_check", sql`${t.kind} in ('batch', 'upload', 'admit', 'complete', 'cancel', 'retry', 'restore', 'undo')`),
  check("ebook_upload_operations_state_check", sql`${t.state} in ('queued', 'admitted', 'receiving', 'ready', 'processing', 'quiescing', 'completed', 'failed', 'canceled', 'expired')`),
  check("ebook_upload_operations_hashes_check", sql`${t.requestSha256} ~ '^[a-f0-9]{64}$' and ${t.targetFingerprint} ~ '^[a-f0-9]{64}$' and ${t.bindingSha256} ~ '^[a-f0-9]{64}$'`),
  check("ebook_upload_operations_protocol_check", sql`${t.protocolVersion} = 1`),
  check("ebook_upload_operations_json_check", sql`jsonb_typeof(${t.input}) = 'object' and jsonb_typeof(${t.progress}) = 'object' and (${t.receipt} is null or jsonb_typeof(${t.receipt}) = 'object')`),
  check("ebook_upload_operations_json_size_check", sql`octet_length(${t.input}::text) <= 65536 and octet_length(${t.progress}::text) <= 131072 and (${t.receipt} is null or octet_length(${t.receipt}::text) <= 131072)`),
  check("ebook_upload_operations_revision_check", sql`${t.revision} >= 0 and ${t.generation} >= 0`),
  check("ebook_upload_operations_reservation_check", sql`${t.reservedBytes} between 0 and 9143582720`),
  check("ebook_upload_operations_size_check", sql`${t.sourceSizeBytes} is null or ${t.sourceSizeBytes} between 1 and 4294967296`),
  check("ebook_upload_operations_item_check", sql`(${t.kind} = 'upload' and ${t.runId} is not null and ${t.ingestItemId} is not null and ${t.sourceSizeBytes} is not null) or (${t.kind} <> 'upload' and ${t.ingestItemId} is null and ${t.sourceSizeBytes} is null and ${t.reservedBytes} = 0)`),
  // Explicit IS NOT NULL: SQL CHECK accepts UNKNOWN, so BETWEEN alone is insufficient.
  check("ebook_upload_operations_receipt_check", sql`(${t.receipt} is null and ${t.receiptStatus} is null) or (${t.receipt} is not null and ${t.receiptStatus} is not null and ${t.receiptStatus} between 200 and 599)`),
  check("ebook_upload_operations_effect_check", sql`${t.effectCommittedAt} is null or ${t.receipt} is not null`),
  check("ebook_upload_operations_lease_check", sql`(${t.leaseToken} is null and ${t.leaseExpiresAt} is null) or (${t.leaseToken} is not null and ${t.leaseExpiresAt} is not null)`),
  check("ebook_upload_operations_release_check", sql`${t.reservationReleasedAt} is null or (${t.reservedBytes} = 0 and ${t.cleanupVerifiedAt} is not null)`),
  index("ebook_upload_operations_dispatch_idx").on(t.volumeId, t.state, t.createdAt, t.id).where(sql`${t.kind} = 'upload' and ${t.state} in ('queued', 'ready', 'failed', 'quiescing')`),
  index("ebook_upload_operations_retention_idx").on(t.retentionExpiresAt, t.id).where(sql`${t.kind} = 'upload' and ${t.reservedBytes} > 0`),
  index("ebook_upload_operations_run_idx").on(t.runId, t.createdAt, t.id),
  index("ebook_upload_operations_parent_idx").on(t.parentOperationId),
]);
